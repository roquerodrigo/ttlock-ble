"""LockErrorCode: the error byte a lock sends after a FAILED status."""

from __future__ import annotations

from enum import IntEnum


class LockErrorCode(IntEnum):
    """Error code in `data[0]` of a FAILED response (mirrors the official SDK's `Error`)."""

    LOCK_CRC_CHECK_ERROR = 0x01
    LOCK_NO_PERMISSION = 0x02
    LOCK_ADMIN_CHECK_ERROR = 0x03
    LOCK_IS_IN_SETTING_MODE = 0x05
    LOCK_NOT_EXIST_ADMIN = 0x06
    LOCK_IS_IN_NO_SETTING_MODE = 0x07
    LOCK_DYNAMIC_PWD_ERROR = 0x08
    LOCK_NO_POWER = 0x0A
    LOCK_INIT_KEYBOARD_FAILED = 0x0B
    LOCK_KEY_FLAG_INVALID = 0x0D
    LOCK_USER_TIME_EXPIRED = 0x0E
    LOCK_PASSWORD_LENGTH_INVALID = 0x0F
    LOCK_SUPER_PASSWORD_IS_SAME_WITH_DELETE_PASSWORD = 0x10
    LOCK_USER_TIME_INEFFECTIVE = 0x11
    LOCK_USER_NOT_LOGIN = 0x12
    LOCK_OPERATE_FAILED = 0x13
    LOCK_PASSWORD_EXIST = 0x14
    LOCK_PASSWORD_NOT_EXIST = 0x15
    LOCK_NO_FREE_MEMORY = 0x16
    IC_CARD_NOT_EXIST = 0x18
    DUPLICATE_DATA = 0x19
    FR_NOT_EXIST = 0x1A
    INVALID_COMMAND = 0x1B
    LOCK_FROZEN = 0x1C
    INVALID_VENDOR = 0x1D
    LOCK_REVERSE = 0x1E
    RECORD_NOT_EXIST = 0x1F
    INVALID_PARAM = 0x20
    PARKING_LOCK_LOCKED_FAILED = 0x21
    COMMAND_RECEIVED = 0x24
    BAD_WIFI_NAME = 0x25
    BAD_WIFI_PASSWORD = 0x26
    RECORD_ALREADY_EXIST = 0x27
    LOW_BATTERY = 0x28
    AES_PARSE_ERROR = 0x30
    KEY_INVALID = 0x31
    LOCK_NOT_SUPPORT_CHANGE_PASSCODE = 0x60
